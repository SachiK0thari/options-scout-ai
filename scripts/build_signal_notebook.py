"""Build notebooks/signal_study.ipynb with executed outputs from evals/signal_study.py.

We generate the notebook programmatically (nbformat-compatible JSON) so the committed outputs are
exactly what the study module printed on the date shown; no hidden manual runs.
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(
    kind: str, source: str, outputs: list[dict[str, object]] | None = None
) -> dict[str, object]:
    c: dict[str, object] = {
        "cell_type": kind,
        "metadata": {},
        "source": source.splitlines(keepends=True),
    }
    if kind == "code":
        c["execution_count"] = 1
        c["outputs"] = outputs or []
    return c


def main() -> int:
    out = subprocess.run(
        [sys.executable, str(ROOT / "evals" / "signal_study.py")],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
        env={"OPTIONS_SCOUT_LOG_LEVEL": "WARNING", "PATH": "/usr/bin:/bin"},
    ).stdout
    nb = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {"name": "python3", "display_name": "Python 3"},
            "language_info": {"name": "python"},
        },
        "cells": [
            cell(
                "markdown",
                "# Signal study: do the Consumer-Trend Score and the bottleneck company score predict anything?\n\n"
                "Section 11.4 of the build spec. **Point-in-time discipline:** each score uses only data dated on or "
                "before the score date; forward returns use closes strictly after it. From Phase 11 the same question is "
                "asked of the bottleneck company score (section 4A.7) with the same rule, and the two are reported "
                "separately and never blended. One observation is one ticker on one date, forward windows do not "
                "overlap, and no confidence interval is printed below 30 independent observations. On the synthetic "
                "fixture corpus the excess-return figures are suppressed: the expected outcome is "
                '"insufficient data", which is not a test of the signal either way.\n\n'
                f"_Notebook generated by `scripts/build_signal_notebook.py` on {datetime.now(tz=UTC):%Y-%m-%d}; "
                "re-run that script to refresh the outputs._",
            ),
            cell(
                "code",
                "import sys\nsys.path.insert(0, '../src')\nfrom pathlib import Path\n"
                "exec(Path('../evals/signal_study.py').read_text())  # defines run_study()\n"
                "from IPython.display import Markdown\nMarkdown(run_study())",
                [
                    {
                        "output_type": "execute_result",
                        "execution_count": 1,
                        "metadata": {},
                        "data": {"text/markdown": out, "text/plain": out},
                    }
                ],
            ),
            cell(
                "markdown",
                "## How to turn this into a real test\n\n"
                "1. Run `python -m options_scout.jobs.refresh_trends --mode live` and `python -m options_scout.jobs.refresh_bottlenecks --mode live` daily; every snapshot is stored with its `as_of` (trend snapshots for 48 hours, bottleneck snapshots for 180 days, since they hold no personal data).\n"
                "2. After 6+ months, join stored scores to realised 30/60/90-day returns (MarketData.app candles) and SPY, one study per signal.\n"
                "3. Pre-register the hypothesis (top-decile 60-day excess return > 0), report the t-interval once 30+ "
                "independent observations exist, the sample size, "
                "and the number of hypotheses tested. Survivorship bias: keep delisted names in the sample.\n",
            ),
        ],
    }
    path = ROOT / "notebooks" / "signal_study.ipynb"
    path.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
