"""Build notebooks/signal_study.ipynb with executed outputs from evals/signal_study.py.

We generate the notebook programmatically (nbformat-compatible JSON) so the committed outputs are
exactly what the study module printed on the date shown — no hidden manual runs.
"""

from __future__ import annotations

import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(kind: str, source: str, outputs: list[dict[str, object]] | None = None) -> dict[str, object]:
    c: dict[str, object] = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
    if kind == "code":
        c["execution_count"] = 1
        c["outputs"] = outputs or []
    return c


def main() -> int:
    out = subprocess.run(
        [sys.executable, str(ROOT / "evals" / "signal_study.py")],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
        env={"OPTIONS_SCOUT_LOG_LEVEL": "WARNING", "PATH": "/usr/bin:/bin"},
    ).stdout
    nb = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3"}, "language_info": {"name": "python"}},
        "cells": [
            cell(
                "markdown",
                "# Signal study — does the Social Arbitrage Score predict anything?\n\n"
                "Section 11.4 of the build spec. **Point-in-time discipline:** each score uses only data dated on or "
                "before the score date; forward returns use closes strictly after it. Whatever the result, it is "
                "reported honestly — a null or insufficient-data result is the expected outcome on a synthetic corpus.\n\n"
                f"_Notebook generated by `scripts/build_signal_notebook.py` on {datetime.now(tz=UTC):%Y-%m-%d}; "
                "re-run that script to refresh the outputs._",
            ),
            cell(
                "code",
                "import sys\nsys.path.insert(0, '../src')\nfrom pathlib import Path\n"
                "exec(Path('../evals/signal_study.py').read_text())  # defines run_study()\n"
                "from IPython.display import Markdown\nMarkdown(run_study())",
                [{"output_type": "execute_result", "execution_count": 1, "metadata": {}, "data": {"text/markdown": out, "text/plain": out}}],
            ),
            cell(
                "markdown",
                "## How to turn this into a real test\n\n"
                "1. Run `python -m options_scout.jobs.refresh_trends --mode live` daily; every snapshot is stored with its `as_of`.\n"
                "2. After 6+ months, join stored scores to realised 30/60/90-day returns (yfinance) and SPY.\n"
                "3. Pre-register the hypothesis (top-decile 60-day excess return > 0), report the CI, the sample size, "
                "and the number of hypotheses tested. Survivorship bias: keep delisted names in the sample.\n",
            ),
        ],
    }
    path = ROOT / "notebooks" / "signal_study.ipynb"
    path.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
